#!/usr/bin/env node
// Reads Microsoft Keyboard Layout Creator files (.klc, as served by
// https://kbdlayout.info/<dll>/download/klc) and writes src/windows-altgr.json: the
// AltGr and Shift+AltGr characters of every Windows layout in src/layouts.json, keyed by
// physical key (KeyboardEvent.code). The .klc files are not committed; re-run with
//   node packages/library/tools/import-klc.mjs <dir with kbdXX.klc files>
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// Scan code -> KeyboardEvent.code (set 1, the typing block only).
export const SCAN = {
  '29': 'Backquote', '02': 'Digit1', '03': 'Digit2', '04': 'Digit3', '05': 'Digit4', '06': 'Digit5', '07': 'Digit6',
  '08': 'Digit7', '09': 'Digit8', '0a': 'Digit9', '0b': 'Digit0', '0c': 'Minus', '0d': 'Equal',
  '10': 'KeyQ', '11': 'KeyW', '12': 'KeyE', '13': 'KeyR', '14': 'KeyT', '15': 'KeyY', '16': 'KeyU', '17': 'KeyI',
  '18': 'KeyO', '19': 'KeyP', '1a': 'BracketLeft', '1b': 'BracketRight', '2b': 'Backslash',
  '1e': 'KeyA', '1f': 'KeyS', '20': 'KeyD', '21': 'KeyF', '22': 'KeyG', '23': 'KeyH', '24': 'KeyJ', '25': 'KeyK',
  '26': 'KeyL', '27': 'Semicolon', '28': 'Quote',
  '56': 'IntlBackslash', '2c': 'KeyZ', '2d': 'KeyX', '2e': 'KeyC', '2f': 'KeyV', '30': 'KeyB', '31': 'KeyN',
  '32': 'KeyM', '33': 'Comma', '34': 'Period', '35': 'Slash',
};

/** One KLC value -> { ch, dead } or null. Values are 4-digit hex, a literal character, -1 or %%. */
function value(v) {
  if (!v || v === '-1' || v === '%%') return null;
  const dead = v.length > 1 && v.endsWith('@');
  const s = dead ? v.slice(0, -1) : v;
  const ch = /^[0-9a-fA-F]{4}$/.test(s) ? String.fromCodePoint(parseInt(s, 16)) : s;
  return { ch, dead };
}

export function parseKlc(text) {
  const lines = text.replace(/\r/g, '').split('\n');
  const out = { altgr: {}, shiftAltgr: {}, dead: [] };
  let section = null;
  const states = [];
  for (const line of lines) {
    const s = line.split('//')[0].trim();
    const word = s.split(/\s+/)[0];
    if (['SHIFTSTATE', 'LAYOUT', 'DEADKEY', 'KEYNAME', 'KEYNAME_EXT', 'KEYNAME_DEAD', 'LIGATURE', 'DESCRIPTIONS', 'LANGUAGENAMES', 'ENDKBD'].includes(word)) { section = word; continue; }
    if (!s) continue;
    if (section === 'SHIFTSTATE') states.push(Number(s));
    if (section !== 'LAYOUT') continue;
    const f = s.split(/\s+/);
    const code = SCAN[f[0].toLowerCase()];
    if (!code) continue;
    f.slice(3).forEach((v, i) => {
      const x = value(v);
      if (!x) return;
      const layer = states[i] === 6 ? 'altgr' : states[i] === 7 ? 'shiftAltgr' : null;
      if (!layer) return;
      out[layer][code] = x.ch;
      if (x.dead) out.dead.push(`${layer === 'altgr' ? '' : 'shift+'}${code}`);
    });
  }
  return out;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const dir = process.argv[2];
  if (!dir) { console.error('usage: import-klc.mjs <dir with kbdXX.klc>'); process.exit(2); }
  const layouts = JSON.parse(readFileSync(join(root, 'src', 'layouts.json'), 'utf8')).layouts;
  const result = { note: 'GENERATED by tools/import-klc.mjs from the .klc files at https://kbdlayout.info/<dll>/download/klc. Physical keys are KeyboardEvent.code.', layouts: {} };
  for (const dll of [...new Set(layouts.map((l) => l.windows).filter(Boolean))].sort()) {
    const file = join(dir, `${dll}.klc`);
    if (!existsSync(file)) { console.error(`missing ${file}`); process.exit(1); }
    const buf = readFileSync(file);
    const text = buf[0] === 0xff && buf[1] === 0xfe ? buf.toString('utf16le').slice(1) : buf.toString('utf8');
    result.layouts[dll] = { source: `https://kbdlayout.info/${dll}/download/klc`, ...parseKlc(text) };
  }
  writeFileSync(join(root, 'src', 'windows-altgr.json'), JSON.stringify(result, null, 1) + '\n');
  console.log(`windows-altgr: ${Object.keys(result.layouts).length} layouts`);
}
