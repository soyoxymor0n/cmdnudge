#!/usr/bin/env node
// Builds dist/library.json from the authored files in src/.
// The interesting part is habitRules: for every habit, layout and keyboard type it works out
// which chord the Mac actually receives when Windows muscle memory presses that habit,
// and drops the rules that would be wrong or noisy (see `reason` in `dropped`).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { arrive, loose, matches, normalize } from '../lib/chord.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => JSON.parse(readFileSync(join(root, 'src', f), 'utf8'));

export const LAYOUTS = ['us', 'de', 'at'];
export const KEYBOARDS = ['apple', 'pc'];

export function build() {
  const { appFamilies } = read('families.json');
  const h = read('habits.json');
  const destructive = h.destructive.chords.map((c) => loose(c));

  const actions = new Map();
  for (const x of h.habits) {
    if (!actions.has(x.action)) {
      actions.set(x.action, { id: x.action, label: x.label, category: x.category, destructive: x.mac.some((m) => destructive.includes(loose(m))) });
    }
  }

  const habitRules = [];
  const dropped = [];
  for (const x of h.habits) {
    for (const layout of x.layouts ?? LAYOUTS) {
      for (const keyboard of x.keyboards ?? KEYBOARDS) {
        const arrives = arrive(x.windows, keyboard);
        const base = { habit: x.id, layout, keyboard, arrives };
        if (x.mac.some((m) => matches(m, arrives))) { dropped.push({ ...base, reason: 'works' }); continue; }
        if ((h.reserved[layout] ?? []).includes(loose(arrives))) { dropped.push({ ...base, reason: 'reserved' }); continue; }
        const shadow = h.habits.find((o) => o.id !== x.id && o.action !== x.action
          && (o.family === x.family || o.family === 'system' || x.family === 'system')
          && (!o.layouts || o.layouts.includes(layout))
          && o.mac.some((m) => matches(m, arrives)));
        // AltGr arrives on the RIGHT ⌘/⌥: the side tells the habit apart from a deliberate press (D7).
        if (shadow && !x.allowShadow && !/(^|\+)r(cmd|opt)\+/.test(arrives)) { dropped.push({ ...base, reason: 'shadow', by: shadow.id }); continue; }
        habitRules.push({
          id: `${x.id}:${layout}:${keyboard}`,
          habit: x.id, action: x.action, family: x.family, layout, keyboard,
          windows: normalize(x.windows, 'win'), arrives, mac: x.mac.map((m) => normalize(m)),
          guard: Boolean(x.guard) && destructive.includes(loose(arrives)),
          category: x.category,
        });
      }
    }
  }

  // The Mac way of each action, so a correct press can be counted (mac_correct).
  const macWays = [];
  const seen = new Set();
  for (const x of h.habits) {
    if (x.teachOnly) continue; // e.g. ⌘Q: pressing it is not "using the habit right"
    for (const m of x.mac) {
      const key = `${x.action}|${x.family}|${normalize(m)}|${(x.layouts ?? LAYOUTS).join(',')}`;
      if (seen.has(key)) continue;
      seen.add(key);
      macWays.push({ action: x.action, family: x.family, chord: normalize(m), layouts: x.layouts ?? LAYOUTS });
    }
  }

  const habits = h.habits.map((x) => ({
    id: x.id, action: x.action, label: x.label, category: x.category, family: x.family,
    windows: normalize(x.windows, 'win'), mac: x.mac.map((m) => normalize(m)), layouts: x.layouts ?? LAYOUTS,
    guard: Boolean(x.guard), note: x.note,
    sourceURL: h.sources[x.src], windowsSourceURL: h.sources[x.winSrc], verifiedOn: x.verifiedOn ?? h.verifiedOn,
  }));

  return {
    schema: 1,
    note: 'GENERATED by packages/library/tools/generate.mjs from src/. Do not edit.',
    layouts: LAYOUTS, keyboards: KEYBOARDS,
    actions: [...actions.values()], appFamilies, habits, habitRules, macWays,
    destructive: h.destructive.chords.map((c) => normalize(c)), dropped,
  };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const lib = build();
  mkdirSync(join(root, 'dist'), { recursive: true });
  writeFileSync(join(root, 'dist', 'library.json'), JSON.stringify(lib, null, 1) + '\n');
  console.log(`library: ${lib.habits.length} habits, ${lib.actions.length} actions, ${lib.habitRules.length} rules, ${lib.dropped.length} dropped, ${lib.macWays.length} mac ways`);
}
